"""Render a reference page per resource type from the CloudFormation schemas.

Run by scripts/build-docs.sh (and CI) before `zensical build`; the output in
docs/reference/ is gitignored, so the pages always match the schemas just downloaded.
"""

import re
from pathlib import Path
from typing import Any

from cfn_typed import typegen

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "reference"


def render(schema: dict[str, Any]) -> str:
    type_name = schema["typeName"]
    parts = type_name.split("::")
    svc = parts[1].lower() + ("_" if parts[1].lower() in typegen.keyword.kwlist else "")  # `lambda_`
    # The same code `cfn-typegen --out cfn_types <type>` writes: nested types first, then
    # Props, the resource dict and the factory.
    module = typegen.render_module("::".join(parts[:2]), [schema])
    head, *blocks = module.split("\n\n\n")
    main, nested = blocks[-3:], blocks[:-3]
    lines = [
        f"# {type_name}",
        "",
        typegen.short(schema.get("description")) or "",
        "",
        f"Generated by `cfn-typegen --out cfn_types {type_name}` into `cfn_types/{svc}.py`:",
        "",
        "```python",
        head.rstrip(),
        "",
        "",
        "\n\n\n".join(main),
        "```",
        "",
    ]
    if nested:
        lines += [
            f'??? note "Nested types ({len(nested)})"',
            "",
            "    These are defined above the properties in the generated module.",
            "",
            "    ```python",
            *["    " + line if line else "" for line in "\n\n\n".join(nested).split("\n")],
            "    ```",
            "",
        ]
    attrs = sorted(typegen.readonly_props(schema))
    if attrs:
        lines += [
            "## Attributes",
            "",
            "Read-only values for `get_att(logical_id, attribute)`. They are not accepted as inputs.",
            "",
            *[f"- `{a}`" for a in attrs],
            "",
        ]
    if url := schema.get("documentationUrl"):
        lines += [f"[AWS documentation]({url})", ""]
    return "\n".join(lines)


def main() -> None:
    wanted = [t for t in (ROOT / "examples" / "types.txt").read_text().split("\n") if t and not t.startswith("#")]
    schemas = typegen.select(typegen.load_schemas(typegen.ensure_schemas(typegen.CACHE)), wanted)
    OUT.mkdir(parents=True, exist_ok=True)
    index = ["# Reference", "", "The Python that `cfn-typegen` writes for each resource, generated from the CloudFormation registry schemas when the book is built.", ""]
    for schema in schemas:
        slug = re.sub(r"\W+", "-", schema["typeName"].replace("AWS::", "")).lower()
        (OUT / f"{slug}.md").write_text(render(schema))
        index.append(f"- [{schema['typeName']}]({slug}.md)")
    (OUT / "index.md").write_text("\n".join(index) + "\n")
    print(f"wrote {len(schemas)} reference pages to {OUT}")


if __name__ == "__main__":
    main()
