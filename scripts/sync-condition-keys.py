"""Regenerate src/cfn_typed/_condition_keys.py: the IAM condition keys of each action, from AWS's Service Authorization Reference.

    uv run scripts/sync-condition-keys.py

AWS publishes one JSON file per service (https://servicereference.us-east-1.amazonaws.com/v1/<prefix>/<prefix>.json) that
lists, for every action, the condition keys it supports. The services are the ones `cfn_typed.permissions` has, so the keys
and the action names cover the same services. Only this script downloads anything; the result is committed.
"""

import json
import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PERMISSIONS = ROOT / "src" / "cfn_typed" / "permissions.py"
OUT = ROOT / "src" / "cfn_typed" / "_condition_keys.py"
URL = "https://servicereference.us-east-1.amazonaws.com/v1/{0}/{0}.json"

HEAD = '''"""IAM condition keys: service prefix -> (the keys of the service, action -> indexes into those keys).

Taken from AWS's Service Authorization Reference (https://docs.aws.amazon.com/service-authorization/latest/reference/),
for the services in `cfn_typed.permissions`. A key written `<key>` or `${TagKey}` stands for any name there, as in
`s3:ExistingObjectTag/<key>`. The global `aws:` keys are not listed. Used by `cfn_typed.iam`.

Generated by scripts/sync-condition-keys.py: do not edit.
"""
# fmt: off
# ruff: noqa

CONDITION_KEYS: dict[str, tuple[tuple[str, ...], dict[str, tuple[int, ...]]]] = {
'''


def services() -> list[str]:
    """The IAM prefixes of `cfn_typed.permissions`, read from the class docstrings the generator writes."""
    return sorted(re.findall(r'"""The `([a-z0-9]+):` actions\."""', PERMISSIONS.read_text()))


def fetch(prefix: str) -> tuple[list[str], dict[str, list[int]]]:
    with urllib.request.urlopen(URL.format(prefix)) as response:
        data = json.load(response)
    keys = sorted({k["Name"] for k in data["ConditionKeys"] if not k["Name"].lower().startswith("aws:")})
    actions: dict[str, list[int]] = {}
    for action in data["Actions"]:
        names = [k for k in action.get("ActionConditionKeys", []) if not k.lower().startswith("aws:")]
        for name in names:
            if name not in keys:
                keys.append(name)
        actions[action["Name"]] = names
    keys.sort()
    return keys, {a: sorted(keys.index(n) for n in names) for a, names in sorted(actions.items()) if names}


def main() -> None:
    rows = []
    for prefix in services():
        keys, actions = fetch(prefix)
        body = ", ".join(f"{a!r}: {tuple(ix)!r}" for a, ix in actions.items())
        rows.append(f"    {prefix!r}: (\n        {tuple(keys)!r},\n        {{{body}}},\n    ),")
        print(f"{prefix}: {len(keys)} keys, {len(actions)} actions with keys")
    OUT.write_text(HEAD + "\n".join(rows) + "\n}\n")
    print(f"wrote {OUT}")


main()
