#!/usr/bin/env -S uv run
# /// script
# requires-python = ">=3.12"
# dependencies = ["awacs==2.6.0"]
# ///
"""Regenerate src/cfn_typed/permissions.py: IAM action names for the major services, taken from awacs.

    uv run scripts/sync-permissions.py

`Sqs.ReceiveMessage` is the string "sqs:ReceiveMessage", so a typo is an attribute error instead of a policy that
quietly allows nothing. The names come from awacs (https://github.com/cloudtools/awacs, BSD-2-Clause), which builds
them from AWS's Service Authorization Reference. awacs is used only here: `uv run` installs it for this script from
the inline metadata above, it is not a dependency of cfn-typed, and the result is committed.

Only exact actions are written. A pattern such as `s3:GetObject*` is a choice about what to grant, so it is an
opinion and lives in `cfn_typed.grants`, not here. To add a service, add it to SERVICES and rerun.
"""

import importlib
import importlib.metadata
import pkgutil
import re
import sys
from pathlib import Path

import awacs
from awacs.aws import Action

OUT = Path(__file__).resolve().parent.parent / "src" / "cfn_typed" / "permissions.py"

# IAM prefix -> class name
SERVICES = {
    "s3": "S3", "dynamodb": "DynamoDb", "sqs": "Sqs", "sns": "Sns", "lambda": "Lambda", "kms": "Kms",
    "secretsmanager": "SecretsManager", "ssm": "Ssm", "logs": "Logs", "events": "Events", "kinesis": "Kinesis",
}


def collect() -> dict[str, list[str]]:
    """IAM prefix -> its exact action names (sorted), read from the awacs service modules."""
    found: dict[str, set[str]] = {}
    for info in pkgutil.iter_modules(awacs.__path__):
        module = importlib.import_module(f"awacs.{info.name}")
        prefix = getattr(module, "prefix", None)
        if prefix not in SERVICES:
            continue
        for name, value in vars(module).items():
            if isinstance(value, Action) and not name.startswith("_") and name != "Action" and value.action:
                found.setdefault(prefix, set()).add(value.action)
    missing = sorted(set(SERVICES) - set(found))
    if missing:
        sys.exit(f"awacs has no module for: {', '.join(missing)}")
    return {prefix: sorted(actions) for prefix, actions in found.items()}


def render(version: str, actions: dict[str, list[str]]) -> str:
    lines = [
        '"""IAM action names, taken from awacs.',
        "",
        '    allow([Sqs.ReceiveMessage, Sqs.DeleteMessage], queue_arn)    # "sqs:ReceiveMessage", ...',
        "",
        "A misspelled name is an attribute error, instead of a policy that quietly allows nothing.",
        "",
        "These are the exact actions of the major services only (not every service in IAM): for anything else, write the",
        "string. A pattern such as `s3:GetObject*` is a choice about what to grant, so it is not here: see",
        "`cfn_typed.grants`.",
        "",
        f"Source: awacs {version} (https://github.com/cloudtools/awacs), BSD-2-Clause, copyright Mark Peek, which builds",
        "its lists from AWS's Service Authorization Reference. See NOTICE and licenses/AWACS-LICENSE.txt.",
        "",
        "Generated by scripts/sync-permissions.py: do not edit.",
        '"""',
        "# fmt: off",
        "# ruff: noqa",
        "",
        "from typing import Final",
    ]
    for prefix in sorted(actions, key=lambda p: SERVICES[p]):
        cls = SERVICES[prefix]
        lines += ["", "", f"class {cls}:", f'    """The `{prefix}:` actions."""', ""]
        seen: set[str] = set()
        for action in actions[prefix]:
            if not re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", action) or action in seen:
                sys.exit(f"cannot make an attribute from {prefix}:{action}")
            seen.add(action)
            lines.append(f'    {action}: Final = "{prefix}:{action}"')
    return "\n".join(lines) + "\n"


def main() -> None:
    version = importlib.metadata.version("awacs")
    actions = collect()
    OUT.write_text(render(version, actions))
    total = sum(map(len, actions.values()))
    print(f"wrote {OUT.relative_to(OUT.parents[2])}: {total} names in {len(actions)} services, {OUT.stat().st_size} bytes (awacs {version})")


if __name__ == "__main__":
    main()
