"""`cfn-typegen init-repo`: scaffold a repository that holds only generated types.

    cfn-typegen init-repo acme-cfn 'AWS::S3::*' 'AWS::Lambda::*'
    cfn-typegen init-repo acme-cfn --dir ~/src/acme-cfn      # no types named: every AWS type

The repository has no hand-written code. `cfn-typegen.toml` says which resource types to
generate, a scheduled workflow regenerates them against fresh schemas and opens a pull
request, and a tag builds and publishes the package.
"""

import argparse
import json
import re
import sys
from pathlib import Path

PYPROJECT = """\
[project]
name = "@NAME@"
version = "0.1.0"
description = "Typed CloudFormation resource definitions, generated by cfn-typegen"
readme = "README.md"
requires-python = ">=3.14"
dependencies = ["cfn-typed"]

[dependency-groups]
dev = ["ty"]

[build-system]
requires = ["hatchling"]
build-backend = "hatchling.build"

[tool.hatch.build.targets.wheel]
packages = ["src/@MODULE@"]
"""

CONFIG = """\
# What cfn-typegen generates; run `cfn-typegen` here with no arguments.
out = "src/@MODULE@"
docs = false  # leave out the description docstrings (much smaller)
@TYPES@
"""

README = """\
# @NAME@

Typed CloudFormation resource definitions, generated by
[cfn-typegen](https://github.com/vivainio/cfn-typed). Nothing in `src/@MODULE@/` is written
by hand: edit `cfn-typegen.toml` and regenerate. Put hand-written helpers in a separate package.

```python
from @MODULE@ import sqs

queue = sqs.queue(QueueName="jobs")
```

## Regenerating

```sh
uv run cfn-typegen --refresh
```

`--refresh` downloads the newest AWS schemas; leave it out to reuse the cached copy. Each
generated module records the schema snapshot it came from. The `refresh` workflow does this
weekly and opens a pull request, and pushing a `v*` tag publishes a release.
"""

GITIGNORE = """\
.venv/
__pycache__/
dist/
"""

REFRESH = """\
name: refresh
on:
  schedule:
    - cron: "0 6 * * 1"
  workflow_dispatch:
permissions:
  contents: write
  pull-requests: write
jobs:
  refresh:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: astral-sh/setup-uv@v5
      - run: uv run cfn-typegen --refresh
      - uses: peter-evans/create-pull-request@v7
        with:
          branch: refresh-schemas
          title: Regenerate types from the latest AWS schemas
          commit-message: Regenerate types from the latest AWS schemas
"""

RELEASE = """\
name: release
on:
  push:
    tags: ["v*"]
permissions:
  id-token: write
jobs:
  release:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: astral-sh/setup-uv@v5
      - run: uv build
      - run: uv publish  # PyPI trusted publishing; for a private index set UV_PUBLISH_URL
"""


def files(name: str, module: str, types: list[str]) -> dict[str, str]:
    selection = f"types = {json.dumps(types)}" if types else "all = true"

    def fill(text: str) -> str:
        return text.replace("@NAME@", name).replace("@MODULE@", module).replace("@TYPES@", selection)

    return {
        "pyproject.toml": fill(PYPROJECT),
        "cfn-typegen.toml": fill(CONFIG),
        "README.md": fill(README),
        ".gitignore": GITIGNORE,
        f"src/{module}/py.typed": "",
        ".github/workflows/refresh.yml": fill(REFRESH),
        ".github/workflows/release.yml": fill(RELEASE),
    }


def init_repo_main(argv: list[str]) -> None:
    ap = argparse.ArgumentParser(
        prog="cfn-typegen init-repo",
        description="Scaffold a repository that publishes generated CloudFormation types.",
    )
    ap.add_argument("name", help="distribution name, e.g. acme-cfn")
    ap.add_argument("types", nargs="*", help="resource types or globs for cfn-typegen.toml (default: every type)")
    ap.add_argument("--dir", type=Path, help="directory to create (default: ./NAME)")
    args = ap.parse_args(argv)

    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9._-]*", args.name):
        ap.error(f"not a valid package name: {args.name}")
    module = re.sub(r"[-.]+", "_", args.name).lower()
    root = args.dir or Path(args.name)
    if root.exists() and any(root.iterdir()):
        sys.exit(f"{root} exists and is not empty")

    for rel, text in files(args.name, module, args.types).items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(f"created {root}. Next:\n  cd {root}\n  uv run cfn-typegen")
