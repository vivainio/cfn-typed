#!/usr/bin/env python3
"""Generate cfn_typed.aws.* TypedDicts and factories from the CloudFormation registry schemas.

    cfn-typegen --out cfn_types AWS::SQS::Queue 'AWS::Lambda::*'
    cfn-typegen --out cfn_types --template template.json   # only the types a template uses
    cfn-typegen --out cfn_types --all                      # everything
    cfn-typegen --out cfn_types --no-docs AWS::SQS::Queue          # without description docstrings
    cfn-typegen search load balancer                               # find type names

Type names are case-insensitive globs. The schema zip is downloaded once into
~/.cache/cfn-typegen/, or pass --schemas to use a local CloudformationSchema.zip.

Each service becomes one module (AWS::SQS::Queue -> <out>/sqs.py) holding,
per resource, a `Queue` dict type, a `QueueProps` properties type, one type per
nested definition, and a factory `queue(**props)` whose keyword arguments are
checked against `QueueProps`. Every property is `Expr[T]`, so intrinsics such as
`Ref` are accepted wherever a literal is.
"""

import argparse
import builtins
import fnmatch
import json
import keyword
import os
import shutil
import re
import sys
import urllib.request
import zipfile
from collections import defaultdict
from pathlib import Path
from typing import Any

SCHEMA_URL = "https://schema.cloudformation.us-east-1.amazonaws.com/CloudformationSchema.zip"
CACHE = Path(os.environ.get("XDG_CACHE_HOME") or Path.home() / ".cache") / "cfn-typegen" / "CloudformationSchema.zip"
MARKER = "# Generated by cfn-typegen"

Schema = dict[str, Any]


def pascal(s: str) -> str:
    out = "".join(p[:1].upper() + p[1:] for p in re.split(r"[^0-9A-Za-z]+", s) if p)
    return "_" + out if out[:1].isdigit() else out


def snake(s: str) -> str:
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s)
    return re.sub(r"[^0-9a-zA-Z]+", "_", s).lower()


def reserved(name: str) -> bool:
    return keyword.iskeyword(name) or hasattr(builtins, name)


def short(desc: str | None) -> str | None:
    """First sentence of a schema description, kept short enough for a docstring."""
    if not desc:
        return None
    text = " ".join(desc.split())
    m = re.match(r"(.+?[.!?])(\s|$)", text)
    text = m.group(1) if m else text
    return text if len(text) <= 160 else text[:157] + "..."


def union(types: list[str]) -> str:
    uniq = list(dict.fromkeys(types))
    return "Any" if "Any" in uniq else " | ".join(uniq)


class Module:
    """Names and class blocks for one service module."""

    def __init__(self) -> None:
        self.names: set[str] = {n for names in IMPORTS.values() for n in names}
        self.blocks: list[str] = []

    def claim(self, base: str) -> str:
        base = base + "_" if reserved(base) else base
        name, i = base, 2
        while name in self.names:
            name, i = f"{base}{i}", i + 1
        self.names.add(name)
        return name


class ResourceGen:
    """Turns one resource schema into TypedDicts inside a Module."""

    def __init__(self, mod: Module, schema: Schema, prefix: str, docs: bool = True) -> None:
        self.mod, self.schema, self.prefix, self.docs = mod, schema, prefix, docs
        self.cache: dict[str, str] = {}
        self.busy: set[str] = set()

    # -- type expressions: always fully wrapped, e.g. `Expr[list[Expr[str]]]` --

    def ty(self, node: Schema, hint: str) -> str:
        if "$ref" in node:
            return self.ref(node["$ref"])
        t = node.get("type")
        if isinstance(t, list):
            return union([self.ty({**node, "type": x}, hint) for x in t])
        if t is None:
            if "properties" in node or "patternProperties" in node:
                t = "object"
            elif "items" in node:
                t = "array"
            elif "enum" in node:
                t = "string"
            else:
                alts = [a for a in node.get("oneOf") or node.get("anyOf") or []
                        if {"type", "$ref", "properties", "items", "enum"} & a.keys()]
                return union([self.ty(a, hint) for a in alts]) if alts else "Any"
        match t:
            case "string":
                return "Expr[str]"
            case "integer":
                return "Expr[int]"
            case "number":
                return "Expr[float]"
            case "boolean":
                return "Expr[bool]"
            case "null":
                return "None"
            case "array":
                items = node.get("items")
                return f"Expr[list[{self.ty(items, hint) if isinstance(items, dict) else 'Any'}]]"
            case "object":
                return self.obj(node, hint)
        return "Any"

    def obj(self, node: Schema, hint: str) -> str:
        if node.get("properties"):
            name = self.mod.claim(hint)
            self.build_class(name, node)
            return f"Expr[{name}]"
        if node.get("patternProperties"):
            val = union([self.ty(v, hint) for v in node["patternProperties"].values()])
        elif isinstance(node.get("additionalProperties"), dict):
            val = self.ty(node["additionalProperties"], hint)
        else:
            val = "Any"
        return f"Expr[Mapping[str, {val}]]"

    def ref(self, ref: str) -> str:
        if ref in self.cache:
            return self.cache[ref]
        if ref in self.busy:  # a cycle through non-object types
            return "Any"
        node: Any = self.schema
        for part in ref.removeprefix("#/").split("/"):
            node = node[part]
        last = ref.rsplit("/", 1)[-1]
        hint = self.prefix + pascal(last)
        props = node.get("properties") or {}
        if last == "Tag" and set(props) == {"Key", "Value"}:
            out = "Expr[Tag]"
        elif props:
            name = self.mod.claim(hint)
            out = self.cache[ref] = f"Expr[{name}]"  # registered first: definitions may be recursive
            self.build_class(name, node)
        else:
            self.busy.add(ref)
            out = self.ty(node, hint)
            self.busy.discard(ref)
        self.cache[ref] = out
        return out

    # -- classes --

    def build_class(self, name: str, node: Schema, skip: frozenset[str] = frozenset()) -> bool:
        """Emit a TypedDict block; returns whether any field is required."""
        required = set(node.get("required", ())) - skip
        fields = [
            (k, self.ty(v, name + pascal(k)), k in required, short(v.get("description")) if self.docs else None)
            for k, v in node.get("properties", {}).items()
            if k not in skip
        ]
        doc = short(node.get("description")) if self.docs else None
        closed = node.get("additionalProperties") is False  # PEP 728: unknown keys become type errors
        if all(k.isidentifier() and not keyword.iskeyword(k) for k, *_ in fields):
            lines = [f"class {name}(TypedDict{', closed=True' if closed else ''}):"]
            if doc:
                lines.append(f"    {doc!r}")
            for k, t, req, fdoc in fields:
                lines.append(f"    {k}: {t if req else f'NotRequired[{t}]'}")
                if fdoc:
                    lines.append(f"    {fdoc!r}")
            if not doc and not fields:
                lines.append("    pass")
        else:  # keys that are not identifiers need the functional syntax
            body = ", ".join(
                f"{k!r}: {t!r}" if req else f"{k!r}: NotRequired[{t!r}]" for k, t, req, _ in fields
            )
            lines = [f"{name} = TypedDict({name!r}, {{{body}}}{', closed=True' if closed else ''})"]
        self.mod.blocks.append("\n".join(lines))
        return any(req for _, _, req, _ in fields)


def readonly_props(schema: Schema) -> frozenset[str]:
    return frozenset(p.split("/")[2] for p in schema.get("readOnlyProperties", []) if p.count("/") == 2)


# Names the generated modules import. Reserved so a schema definition can't shadow them.
IMPORTS = {
    "collections.abc": ["Mapping"],
    "typing": ["Any", "Literal", "NotRequired", "Unpack"],
    "typing_extensions": ["TypedDict"],
    "cfn_typed.base": ["DeletionPolicy", "DependsOn", "ResourceAttrs", "Tag", "UpdateReplacePolicy", "build"],
    "cfn_typed.intrinsics": ["Expr"],
}


def imports(body: str) -> str:
    """One `from x import ...` line per source, listing only the names `body` uses."""
    lines = []
    for source, names in IMPORTS.items():
        used = [n for n in names if re.search(rf"\b{n}\b", body)]
        if used:
            lines.append(f"from {source} import {', '.join(used)}")
    return "\n".join(lines) + "\n"


def render_module(title: str, schemas: list[Schema], docs: bool = True) -> str:
    mod = Module()
    plans = []
    for s in sorted(schemas, key=lambda s: s["typeName"]):
        res = pascal("".join(s["typeName"].split("::")[2:]))
        plans.append((s, mod.claim(res), mod.claim(res + "Props"), mod.claim(snake(res))))
    for schema, res, props_cls, factory in plans:
        type_name = schema["typeName"]
        gen = ResourceGen(mod, schema, res, docs)
        has_required = gen.build_class(props_cls, schema, readonly_props(schema))
        doc = short(schema.get("description")) if docs else None
        mod.blocks.append("\n".join([
            f"class {res}(ResourceAttrs):",
            *([f"    {doc!r}"] if doc else []),
            f"    Type: Literal[{type_name!r}]",
            f"    Properties: {props_cls}" if has_required else f"    Properties: NotRequired[{props_cls}]",
        ]))
        mod.blocks.append("\n".join([
            f"def {factory}(",
            "    *,",
            "    depends_on: DependsOn | None = None,",
            "    deletion_policy: DeletionPolicy | None = None,",
            "    update_replace_policy: UpdateReplacePolicy | None = None,",
            "    condition: str | None = None,",
            "    metadata: dict[str, Any] | None = None,",
            f"    **props: Unpack[{props_cls}],",
            f") -> {res}:",
            f"    return build({type_name!r}, props, depends_on, deletion_policy, update_replace_policy, condition, metadata)",
        ]))
    body = "\n\n\n".join(mod.blocks)
    head = (
        f"{MARKER} from the CloudFormation registry schemas. Do not edit.\n"
        "# fmt: off\n# ruff: noqa\n"  # generated code: formatters and linters leave it alone
        f'"""{title} resources."""\n\n'
    )
    head += imports(body)
    return head + "\n\n" + body + "\n"


def ensure_schemas(path: Path) -> Path:
    """Return `path`, downloading the schema zip there first if it is missing."""
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        print(f"downloading {SCHEMA_URL}")
        urllib.request.urlretrieve(SCHEMA_URL, path)
    return path


def load_schemas(zip_path: Path) -> list[Schema]:
    with zipfile.ZipFile(zip_path) as zf:
        return [json.loads(zf.read(n)) for n in sorted(zf.namelist()) if n.endswith(".json")]


def template_types(path: Path) -> list[str]:
    resources = json.loads(path.read_text()).get("Resources", {})
    return sorted({r["Type"] for r in resources.values() if "Type" in r})


def select(schemas: list[Schema], patterns: list[str]) -> list[Schema]:
    wanted = [p.lower() for p in patterns]
    missing = [p for p in wanted if not any(fnmatch.fnmatchcase(s["typeName"].lower(), p) for s in schemas)]
    if missing:
        sys.exit(f"no resource type matches: {', '.join(missing)}")
    return [s for s in schemas if any(fnmatch.fnmatchcase(s["typeName"].lower(), p) for p in wanted)]


def write(out: Path, schemas: list[Schema], docs: bool = True) -> None:
    groups: dict[str, list[Schema]] = defaultdict(list)
    for schema in schemas:
        parts = schema["typeName"].split("::")
        if len(parts) < 3:
            print(f"skipping {schema['typeName']}", file=sys.stderr)
            continue
        svc = parts[1].lower()
        groups[svc + "_" if keyword.iskeyword(svc) else svc].append(schema)
    out.mkdir(parents=True, exist_ok=True)
    for f in out.glob("*.py"):  # drop only what an earlier run generated
        if f.read_text().startswith(MARKER):
            f.unlink()
    (out / "__init__.py").write_text(f'{MARKER}.\n"""Generated CloudFormation resource modules, one per service."""\n')
    for svc, items in sorted(groups.items()):
        title = "::".join(items[0]["typeName"].split("::")[:2])
        (out / f"{svc}.py").write_text(render_module(title, items, docs))
    print(f"wrote {sum(map(len, groups.values()))} resources in {len(groups)} modules to {out}")


_BOILERPLATE = re.compile(r"Resource (type definition|schema) for [\w:]+\.?", re.I)  # says nothing the name does not


def search(schemas: list[Schema], terms: list[str]) -> list[Schema]:
    """Schemas whose name or description contains every term, best matches first.

    A hit in the resource's own name beats a hit anywhere in the type name, which beats a
    hit only in the description; shorter names come first within each group.
    """
    words = [t.lower() for t in terms]
    ranked = []
    for schema in schemas:
        name = schema["typeName"].lower()
        resource = name.rsplit("::", 1)[-1]
        text = name + " " + (schema.get("description") or "").lower()
        if not all(w in text for w in words):
            continue
        tier = 0 if all(w in resource for w in words) else 1 if all(w in name for w in words) else 2
        ranked.append((tier, len(name), name, schema))
    return [schema for *_, schema in sorted(ranked, key=lambda r: r[:3])]


def search_main(argv: list[str]) -> None:
    ap = argparse.ArgumentParser(
        prog="cfn-typegen search",
        description="Find resource types by words in their name or description, then pass the names to cfn-typegen.",
    )
    ap.add_argument("terms", nargs="+", help="words that must all match, e.g. load balancer")
    ap.add_argument("--limit", type=int, default=20, help="most results to show (default 20)")
    ap.add_argument("--schemas", type=Path, default=CACHE, help="CloudformationSchema.zip (downloaded if missing)")
    args = ap.parse_args(argv)

    found = search(load_schemas(ensure_schemas(args.schemas)), args.terms)
    shown = found[: args.limit]
    width = max((len(s["typeName"]) for s in shown), default=0)
    columns = shutil.get_terminal_size((100, 24)).columns
    for schema in shown:
        desc = short(schema.get("description")) or ""
        desc = "" if _BOILERPLATE.fullmatch(desc) else desc
        room = max(columns - width - 3, 0)
        print(f"{schema['typeName']:<{width}}  {desc[:room]}".rstrip())
    sys.stdout.flush()
    if not found:
        sys.exit(f"no resource type matches: {' '.join(args.terms)}")
    more = f" (showing {len(shown)}, use --limit)" if len(found) > len(shown) else ""
    print(f"\n{len(found)} match{'es' if len(found) != 1 else ''}{more}. Generate with: cfn-typegen --out DIR <type>...", file=sys.stderr)


def main(argv: list[str] | None = None) -> None:
    argv = sys.argv[1:] if argv is None else argv
    if argv[:1] == ["search"]:
        return search_main(argv[1:])
    ap = argparse.ArgumentParser(prog="cfn-typegen", description="Generate typed CloudFormation resource modules.", epilog="Not sure of a type name? Run: cfn-typegen search WORD...")
    ap.add_argument("types", nargs="*", help="resource types or globs, e.g. AWS::SQS::Queue or 'AWS::Lambda::*'")
    ap.add_argument("--out", type=Path, required=True, help="directory to write the modules into")
    ap.add_argument("--template", type=Path, action="append", default=[], help="JSON template; emit the types it uses")
    ap.add_argument("--all", action="store_true", help="emit every resource type")
    ap.add_argument("--no-docs", action="store_true", help="leave the description docstrings out (much smaller output)")
    ap.add_argument("--schemas", type=Path, default=CACHE, help="CloudformationSchema.zip (downloaded if missing)")
    args = ap.parse_args(argv)

    patterns = args.types + [t for path in args.template for t in template_types(path)]
    if not patterns and not args.all:
        ap.error("name resource types, pass --template, or use --all")
    schemas = load_schemas(ensure_schemas(args.schemas))
    write(args.out, schemas if args.all else select(schemas, patterns), docs=not args.no_docs)


if __name__ == "__main__":
    main()
