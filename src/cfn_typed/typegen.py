MARKER = "# Generated by cfn-typegen"

Schema = dict[str, Any]


def pascal(s: str) -> str:
    out = "".join(p[:1].upper() + p[1:] for p in re.split(r"[^0-9A-Za-z]+", s) if p)
    return "_" + out if out[:1].isdigit() else out


def snake(s: str) -> str:
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s)
    return re.sub(r"[^0-9a-zA-Z]+", "_", s).lower()


def reserved(name: str) -> bool:
    return keyword.iskeyword(name) or hasattr(builtins, name)


def short(desc: str | None) -> str | None:
    """First sentence of a schema description, kept short enough for a docstring."""
    if not desc:
        return None
    text = " ".join(desc.split())
    m = re.match(r"(.+?[.!?])(\s|$)", text)
    text = m.group(1) if m else text
    return text if len(text) <= 160 else text[:157] + "..."


def union(types: list[str]) -> str:
    uniq = list(dict.fromkeys(types))
    return "Any" if "Any" in uniq else " | ".join(uniq)


class Module:
    """Names and class blocks for one service module."""

    def __init__(self, siblings: Collection[str] = ()) -> None:
        self.names: set[str] = {n for names in IMPORTS.values() for n in names}
        self.siblings = set(siblings)  # resource names of the service, generated or not
        self.blocks: list[str] = []

    def claim(self, base: str, *, resource: bool = False) -> str:
        """A free name. A property type whose name is a resource name of the service gets `Property` added, so
        `Role.Policy` is `RolePolicyProperty` whether or not `AWS::IAM::RolePolicy` is among the types being generated."""
        base = base + "_" if reserved(base) else base
        if not resource and base in self.siblings:
            base += "Property"
        name, i = base, 2
        while name in self.names:
            name, i = f"{base}{i}", i + 1
        self.names.add(name)
        return name


class ResourceGen:
    """Turns one resource schema into TypedDicts inside a Module."""

    def __init__(self, mod: Module, schema: Schema, prefix: str, docs: bool = True, literal_enums: bool = False) -> None:
        self.mod, self.schema, self.prefix, self.docs, self.literal_enums = mod, schema, prefix, docs, literal_enums
        self.cache: dict[str, str] = {}
        self.busy: set[str] = set()
        self.known: dict[str, Schema | None] = {}  # constraints of each definition, shared by every use
        self.cut: set[str] = set()  # definitions a cycle was cut at, until that definition finishes

    # -- type expressions: always fully wrapped, e.g. `Expr[list[Expr[str]]]` --

    def ty(self, node: Schema, hint: str) -> str:
        if "$ref" in node:
            return self.ref(node["$ref"])
        t = node.get("type")
        if isinstance(t, list):
            return union([self.ty({**node, "type": x}, hint) for x in t])
        if t is None:
            if "properties" in node or "patternProperties" in node:
                t = "object"
            elif "items" in node:
                t = "array"
            elif "enum" in node:
                t = "string"
            else:
                alts = [a for a in node.get("oneOf") or node.get("anyOf") or []
                        if {"type", "$ref", "properties", "items", "enum"} & a.keys()]
                return union([self.ty(a, hint) for a in alts]) if alts else "Any"
        match t:
            case "string":
                if isinstance(node.get("x-literal"), str):  # set by samschema for a field with one possible value
                    return f"Expr[Literal[{node['x-literal']!r}]]"
                return self.scalar(node, "Expr[str]")
            case "integer":
                return self.scalar(node, "Expr[int]")
            case "number":
                return "Expr[float]"
            case "boolean":
                return "Expr[bool]"
            case "null":
                return "None"
            case "array":
                items = node.get("items")
                inner = self.ty(items, hint) if isinstance(items, dict) else "Any"
                # Sequence is covariant, so a list of plain dicts fits a list of Expr[...]; a str is a Sequence[str], so strings keep list
                return f"Expr[list[{inner}]]" if inner == "Expr[str]" else f"Expr[Sequence[{inner}]]"
            case "object":
                return self.obj(node, hint)
        return "Any"

    def scalar(self, node: Schema, base: str) -> str:
        """`base`, or the schema's allowed values as a `Literal` when `literal_enums` is on."""
        enum = node.get("enum")
        if self.literal_enums and enum and all(isinstance(e, (str, int)) and not isinstance(e, bool) for e in enum):
            return f"Expr[Literal[{', '.join(repr(e) for e in enum)}]]"
        return base

    def obj(self, node: Schema, hint: str) -> str:
        if node.get("properties"):
            name = self.mod.claim(hint)
            self.build_class(name, node)
            return f"Expr[{name}]"
        if node.get("patternProperties"):
            val = union([self.ty(v, hint) for v in node["patternProperties"].values()])
        elif isinstance(node.get("additionalProperties"), dict):
            val = self.ty(node["additionalProperties"], hint)
        else:
            val = "Any"
        return f"Expr[Mapping[str, {val}]]"

    def ref(self, ref: str) -> str:
        if ref in self.cache:
            return self.cache[ref]
        if ref in self.busy:  # a cycle through non-object types
            return "Any"
        node = self.deref(ref)
        last = ref.rsplit("/", 1)[-1]
        hint = self.prefix + pascal(last)
        props = node.get("properties") or {}
        if last == "Tag" and set(props) == {"Key", "Value"}:
            out = "Expr[Tag]"
        elif props:
            name = self.mod.claim(hint)
            out = self.cache[ref] = f"Expr[{name}]"  # registered first: definitions may be recursive
            self.build_class(name, node)
        else:
            self.busy.add(ref)
            out = self.ty(node, hint)
            self.busy.discard(ref)
        self.cache[ref] = out
        return out

    def deref(self, ref: str) -> Schema:
        node: Any = self.schema
        for part in ref.removeprefix("#/").split("/"):
            node = node[part]
        return node

    # -- value constraints: the checkable keywords, as a nested dict that mirrors the properties --

    def constraints(self, node: Schema, seen: tuple[str, ...] = ()) -> Schema | None:
        """The constraints at and under `node`, or None when there are none. A node is a dict with any of the
        leaf keywords plus `props` (name -> node), `items` (node) and `values` (node, for a map's values)."""
        if "$ref" in node:
            ref = node["$ref"]
            if ref in seen:  # a cycle is cut where it closes
                self.cut.add(ref)
                return None
            if ref not in self.known:
                found = self.constraints(self.deref(ref), (*seen, ref))
                self.cut.discard(ref)
                if self.cut:  # cut at a definition further out: this result depends on the path, so do not reuse it
                    return found
                self.known[ref] = found
            return self.known[ref]
        out: Schema = {k: node[k] for k in LEAF_CONSTRAINTS if k in node and checkable(k, node[k])}
        if props := {k: c for k, v in node.get("properties", {}).items() if (c := self.constraints(v, seen))}:
            out["props"] = props
        items = node.get("items")
        if isinstance(items, dict) and (c := self.constraints(items, seen)):
            out["items"] = c
        if not node.get("properties"):
            patterns = node.get("patternProperties")
            value = next(iter(patterns.values())) if patterns else node.get("additionalProperties")
            if isinstance(value, dict) and (c := self.constraints(value, seen)):
                out["values"] = c
        return out or None

    # -- combination rules: which properties must, or must not, be set together --

    def rules(self, node: Schema, path: tuple[str, ...] = (), seen: tuple[str, ...] = ()) -> list[Any]:
        """`[path, kind, data]` for each combination rule at and under `node`; see `cfn_typed.combinations`.
        `path` names the properties down to the object a rule is about, with "[]" for list items and "*" for map values."""
        if "$ref" in node:
            ref = node["$ref"]
            return [] if ref in seen else self.rules(self.deref(ref), path, (*seen, ref))
        out: list[Any] = [[list(path), kind, data] for kind, data in node_rules(node)]
        for name, v in node.get("properties", {}).items():
            out += self.rules(v, (*path, name), seen)
        items = node.get("items")
        if isinstance(items, dict):
            out += self.rules(items, (*path, "[]"), seen)
        if not node.get("properties"):
            patterns = node.get("patternProperties")
            value = next(iter(patterns.values())) if patterns else node.get("additionalProperties")
            if isinstance(value, dict):
                out += self.rules(value, (*path, "*"), seen)
        return out

    # -- classes --

    def build_class(self, name: str, node: Schema, skip: frozenset[str] = frozenset(), optional: frozenset[str] = frozenset(), force: frozenset[str] = frozenset()) -> bool:
        """Emit a TypedDict block; returns whether any field is required. `optional` relaxes required fields, `force` requires others."""
        required = (set(node.get("required", ())) - skip - optional) | (force & node.get("properties", {}).keys())
        fields = [
            (k, self.ty(v, name + pascal(k)), k in required, short(v.get("description")) if self.docs else None)
            for k, v in node.get("properties", {}).items()
            if k not in skip
        ]
        doc = short(node.get("description")) if self.docs else None
        closed = node.get("additionalProperties") is False  # PEP 728: unknown keys become type errors
        if all(k.isidentifier() and not keyword.iskeyword(k) for k, *_ in fields):
            lines = [f"class {name}(TypedDict{', closed=True' if closed else ''}):"]
            if doc:
                lines.append(f"    {doc!r}")
            for k, t, req, fdoc in fields:
                lines.append(f"    {k}: {t if req else f'NotRequired[{t}]'}")
                if fdoc:
                    lines.append(f"    {fdoc!r}")
            if not doc and not fields:
                lines.append("    pass")
        else:  # keys that are not identifiers need the functional syntax
            body = ", ".join(
                f"{k!r}: {t!r}" if req else f"{k!r}: NotRequired[{t!r}]" for k, t, req, _ in fields
            )
            lines = [f"{name} = TypedDict({name!r}, {{{body}}}{', closed=True' if closed else ''})"]
        self.mod.blocks.append("\n".join(lines))
        return any(req for _, _, req, _ in fields)


# Where the registry's `required` list differs from cfn-lint's bundled schemas (of ~1,800 types, only these three).
# A nested stack gets a generated name and cannot be created without a template. QuotaShareName is taken from
# cfn-lint without independent confirmation.
DEFAULT_OPTIONAL = ["AWS::CloudFormation::Stack.StackName"]
DEFAULT_REQUIRED = ["AWS::CloudFormation::Stack.TemplateURL", "AWS::Batch::QuotaShare.QuotaShareName"]
DEFAULT_UNCONSTRAINED: list[str] = []  # properties whose registry constraints are known to be wrong


def prop_overrides(entries: list[str]) -> dict[str, frozenset[str]]:
    """`["AWS::X::Y.Prop", ...]` as {type name: its properties}."""
    out: dict[str, set[str]] = defaultdict(set)
    for entry in entries:
        type_name, dot, prop = entry.rpartition(".")
        if not dot or not prop:
            sys.exit(f"optional and required entries look like AWS::Service::Resource.Property, got {entry!r}")
        out[type_name].add(prop)
    return {k: frozenset(v) for k, v in out.items()}


class Overrides(NamedTuple):
    """Top-level properties whose `required` status differs from the registry schema."""

    optional: dict[str, frozenset[str]]
    required: dict[str, frozenset[str]]
    unconstrained: dict[str, frozenset[str]]  # no value constraints are generated for these

    @classmethod
    def of(cls, optional: list[str] | None = None, required: list[str] | None = None, unconstrained: list[str] | None = None) -> "Overrides":
        return cls(
            prop_overrides([*DEFAULT_OPTIONAL, *(optional or [])]),
            prop_overrides([*DEFAULT_REQUIRED, *(required or [])]),
            prop_overrides([*DEFAULT_UNCONSTRAINED, *(unconstrained or [])]),
        )


LEAF_CONSTRAINTS = ("enum", "pattern", "minLength", "maxLength", "minimum", "maximum", "minItems", "maxItems")


def checkable(key: str, value: Any) -> bool:
    """Whether the validator can use this constraint: scalar enums, patterns Python can compile, plain numbers."""
    if key == "enum":
        return isinstance(value, list) and all(isinstance(e, (str, int, float)) for e in value)
    if key == "pattern":
        try:
            re.compile(value)
        except (re.error, TypeError):
            return False  # written for another regex dialect: leave it unchecked rather than guess
        return True
    return isinstance(value, (int, float)) and not isinstance(value, bool)


_BRANCH_KEYS = {"required", "title", "description", "type"}


def node_rules(node: Schema) -> list[tuple[str, Any]]:
    """The combination rules a schema object states itself, as (kind, data): `o` exactly one of the branches
    (each a list of property names that must all be set), `a` at least one, `d` {property: properties it needs}.
    Branches that are not plain `required` lists (type unions, nested schemas) are left to the type checker."""
    out: list[tuple[str, Any]] = []
    for kind, key in (("o", "oneOf"), ("a", "anyOf")):
        branches = node.get(key)
        if isinstance(branches, list) and branches and all(
            isinstance(b, dict) and isinstance(b.get("required"), list) and set(b) <= _BRANCH_KEYS for b in branches
        ):
            out.append((kind, [list(b["required"]) for b in branches]))
    for key in ("dependencies", "dependentRequired"):
        deps = {k: list(v) for k, v in (node.get(key) or {}).items() if isinstance(v, list) and all(isinstance(x, str) for x in v)}
        if deps:
            out.append(("d", deps))
    for part in node.get("allOf", []):
        if isinstance(part, dict):
            out += node_rules(part)
    return out


def constraint_source(table: Schema) -> str:
    """Python source for the CONSTRAINTS table, as small as it will go: short keys (see `cfn_typed.constraints`), no
    spaces, and a node used more than once, or a long value repeated, written once as a named constant."""
    seen: Counter[int] = Counter()
    values: Counter[str] = Counter()

    def children(n: Schema) -> list[Schema]:
        return [*n.get("props", {}).values(), *(n[k] for k in ("items", "values") if k in n)]

    def count(n: Schema) -> None:
        seen[id(n)] += 1
        if seen[id(n)] == 1:
            for key in SHORT:
                if key in n:
                    values[dump(n[key])] += 1
            for child in children(n):
                count(child)

    for props in table.values():
        for node in props.values():
            count(node)
    names: dict[object, str] = {}
    shared: list[str] = []

    def name(key: object, src: str) -> str:
        if key not in names:
            names[key] = f"_c{len(shared)}"
            shared.append(f"{names[key]}={src}")
        return names[key]

    def leaf(v: Any) -> str:
        src = dump(v)
        return name(src, src) if values[src] > 1 and len(src) > 24 else src

    def expr(n: Schema) -> str:
        if id(n) in names:
            return names[id(n)]
        parts = [f"{SHORT[k]!r}:{leaf(v)}" for k, v in n.items() if k in SHORT]
        if "props" in n:
            parts.append(f"{PROPS!r}:{{{','.join(f'{p!r}:{expr(c)}' for p, c in n['props'].items())}}}")
        parts += [f"{key!r}:{expr(n[long])}" for long, key in (("items", ITEMS), ("values", VALUES)) if long in n]
        src = "{" + ",".join(parts) + "}"
        return name(id(n), src) if seen[id(n)] > 1 and children(n) else src

    lines = [f"{t!r}:{{" + ",".join(f"{p!r}:{expr(n)}" for p, n in props.items()) + "}," for t, props in table.items()]
    return "\n".join([*shared, "CONSTRAINTS:dict[str,Any]={", *lines, "}"])


def dump(value: Any) -> str:
    return json.dumps(value, separators=(",", ":"))  # a JSON scalar or list is also a Python literal here


def readonly_props(schema: Schema) -> frozenset[str]:
    return frozenset(p.split("/")[2] for p in schema.get("readOnlyProperties", []) if p.count("/") == 2)


def attribute_names(schema: Schema) -> list[str]:
    """What `Fn::GetAtt` may ask this resource for: its read-only and identifier properties, as `Outer.Inner` for nested ones."""
    paths = [*schema.get("readOnlyProperties", []), *schema.get("primaryIdentifier", [])]
    return sorted({".".join(p.split("/")[2:]) for p in paths if "*" not in p.split("/")})


# Names the generated modules import. Reserved so a schema definition can't shadow them.
IMPORTS = {
    "collections.abc": ["Mapping", "Sequence"],
    "typing": ["Any", "Literal", "NotRequired", "Unpack"],
    "typing_extensions": ["TypedDict"],
    "cfn_typed.base": ["DeletionPolicy", "DependsOn", "ResourceAttrs", "Tag", "UpdateReplacePolicy", "build"],
    "cfn_typed.intrinsics": ["Expr"],
}


def imports(body: str) -> str:
    """One `from x import ...` line per source, listing only the names `body` uses."""
    lines = []
    for source, names in IMPORTS.items():
        used = [n for n in names if re.search(rf"\b{n}\b", body)]
        if used:
            lines.append(f"from {source} import {', '.join(used)}")
    return "\n".join(lines) + "\n"


def resource_name(schema: Schema) -> str:
    return pascal("".join(schema["typeName"].split("::")[2:]))


def sam_factory_body(type_name: str) -> list[str]:
    """SAM allows `Connectors` and `IgnoreGlobals` beside `Properties`; `build` does not know them."""
    return [
        f"    out = build({type_name!r}, props, depends_on, deletion_policy, update_replace_policy, condition, metadata)",
        "    if connectors is not None:",
        "        out['Connectors'] = connectors",
        "    if ignore_globals is not None:",
        "        out['IgnoreGlobals'] = ignore_globals",
        "    return out",
    ]


def render_module(title: str, schemas: list[Schema], docs: bool = True, stamp: str | None = None, overrides: Overrides | None = None, constraints: bool = True, literal_enums: bool = False, siblings: Collection[str] = ()) -> str:
    mod = Module(siblings)
    table: dict[str, Schema] = {}
    attributes: dict[str, list[str]] = {}
    combinations: dict[str, list[Any]] = {}
    plans = []
    for s in sorted(schemas, key=lambda s: s["typeName"]):
        res = resource_name(s)
        plans.append((s, mod.claim(res, resource=True), mod.claim(res + "Props", resource=True), mod.claim(snake(res), resource=True)))
    for schema, res, props_cls, factory in plans:
        type_name = schema["typeName"]
        gen = ResourceGen(mod, schema, res, docs, literal_enums)
        ov = overrides or Overrides.of()
        sam = bool(schema.get("x-sam"))
        if constraints:
            if not sam:  # SAM resources have `Ref`/`GetAtt` values the schema does not list: leave them unchecked
                attributes[type_name] = attribute_names(schema)
            if found := gen.rules(schema):
                combinations[type_name] = found
            top = (gen.constraints(schema) or {}).get("props", {})
            top = {k: v for k, v in top.items() if k not in ov.unconstrained.get(type_name, ())}
            if top:
                table[type_name] = top
        has_required = gen.build_class(props_cls, schema, readonly_props(schema), ov.optional.get(type_name, frozenset()), ov.required.get(type_name, frozenset()))
        doc = short(schema.get("description")) if docs else None
        mod.blocks.append("\n".join([
            f"class {res}(ResourceAttrs):",
            *([f"    {doc!r}"] if doc else []),
            f"    Type: Literal[{type_name!r}]",
            f"    Properties: {props_cls}" if has_required else f"    Properties: NotRequired[{props_cls}]",
            *(["    Connectors: NotRequired[Mapping[str, Any]]", "    IgnoreGlobals: NotRequired[str | Sequence[str]]"] if sam else []),
        ]))
        mod.blocks.append("\n".join([
            f"def {factory}(",
            "    *,",
            "    depends_on: DependsOn | None = None,",
            "    deletion_policy: DeletionPolicy | None = None,",
            "    update_replace_policy: UpdateReplacePolicy | None = None,",
            "    condition: str | None = None,",
            "    metadata: dict[str, Any] | None = None,",
            *(["    connectors: Mapping[str, Any] | None = None,", "    ignore_globals: str | Sequence[str] | None = None,"] if sam else []),
            f"    **props: Unpack[{props_cls}],",
            f") -> {res}:",
            *(sam_factory_body(type_name) if sam else [f"    return build({type_name!r}, props, depends_on, deletion_policy, update_replace_policy, condition, metadata)"]),
        ]))
    if constraints:
        mod.blocks.append(constraint_source(table))
        mod.blocks.append(f"ATTRIBUTES:dict[str,Any]={dump(attributes)}")
        mod.blocks.append(f"RULES:dict[str,Any]={dump(combinations)}")
    body = "\n\n\n".join(mod.blocks)
    head = f"{MARKER} from the CloudFormation registry schemas. Do not edit.\n"
    head += "# fmt: off\n# ruff: noqa\n"  # generated code: formatters and linters leave it alone
    if stamp:
        head += f"# Schema snapshot: {stamp}\n"
    head += f'"""{title} resources."""\n\n' + imports(body)
    return head + "\n\n" + body + "\n"


def ensure_schemas(path: Path, refresh: bool = False) -> Path:
    """Return `path`, downloading the schema zip there first if it is missing (or `refresh`)."""
    if refresh or not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        print(f"downloading {SCHEMA_URL}")
        partial = path.with_name(path.name + ".part")  # a failed download must not clobber a good cache
        try:
            urllib.request.urlretrieve(SCHEMA_URL, partial)
            os.replace(partial, path)
        except BaseException:
            partial.unlink(missing_ok=True)
            raise
    return path


def schema_stamp(zip_path: Path) -> str:
    """`sha256:<12 hex>` of the schema zip: which AWS snapshot generated code came from."""
    return "sha256:" + hashlib.sha256(zip_path.read_bytes()).hexdigest()[:12]


def load_schemas(zip_path: Path) -> list[Schema]:
    with zipfile.ZipFile(zip_path) as zf:
        return [json.loads(zf.read(n)) for n in sorted(zf.namelist()) if n.endswith(".json")]


def template_types(path: Path) -> list[str]:
    resources = json.loads(path.read_text()).get("Resources", {})
    return sorted({r["Type"] for r in resources.values() if "Type" in r})


def select(schemas: list[Schema], patterns: list[str]) -> list[Schema]:
    wanted = [p.lower() for p in patterns]
    missing = [p for p in wanted if not any(fnmatch.fnmatchcase(s["typeName"].lower(), p) for s in schemas)]
    if missing:
        sys.exit(f"no resource type matches: {', '.join(missing)}")
    return [s for s in schemas if any(fnmatch.fnmatchcase(s["typeName"].lower(), p) for p in wanted)]


def write(out: Path, schemas: list[Schema], docs: bool = True, stamp: str | None = None, overrides: Overrides | None = None, constraints: bool = True, literal_enums: bool = False, universe: list[Schema] | None = None) -> None:
    """`universe` is every schema of the registry: it keeps property type names the same whichever types are selected."""
    siblings: dict[str, set[str]] = defaultdict(set)
    for schema in universe or schemas:
        if len(parts := schema["typeName"].split("::")) >= 3:
            siblings[parts[1].lower()].add(resource_name(schema))
    groups: dict[str, list[Schema]] = defaultdict(list)
    for schema in schemas:
        parts = schema["typeName"].split("::")
        if len(parts) < 3:
            print(f"skipping {schema['typeName']}", file=sys.stderr)
            continue
        svc = parts[1].lower()
        groups[svc + "_" if keyword.iskeyword(svc) else svc].append(schema)
    out.mkdir(parents=True, exist_ok=True)
    for f in out.glob("*.py"):  # drop only what an earlier run generated
        if f.read_text().startswith(MARKER):
            f.unlink()
    (out / "__init__.py").write_text(f'{MARKER}.\n"""Generated CloudFormation resource modules, one per service."""\n')
    for svc, items in sorted(groups.items()):
        title = "::".join(items[0]["typeName"].split("::")[:2])
        (out / f"{svc}.py").write_text(render_module(title, items, docs, stamp, overrides, constraints, literal_enums, siblings[items[0]["typeName"].split("::")[1].lower()]))
    print(f"wrote {sum(map(len, groups.values()))} resources in {len(groups)} modules to {out}")


_BOILERPLATE = re.compile(r"Resource (type definition|schema) for [\w:]+\.?", re.I)  # says nothing the name does not


def search(schemas: list[Schema], terms: list[str]) -> list[Schema]:
    """Schemas whose name or description contains every term, best matches first.

    A hit in the resource's own name beats a hit anywhere in the type name, which beats a
    hit only in the description; shorter names come first within each group.
    """
    words = [t.lower() for t in terms]
    ranked = []
    for schema in schemas:
        name = schema["typeName"].lower()
        resource = name.rsplit("::", 1)[-1]
        text = name + " " + (schema.get("description") or "").lower()
        if not all(w in text for w in words):
            continue
        tier = 0 if all(w in resource for w in words) else 1 if all(w in name for w in words) else 2
        ranked.append((tier, len(name), name, schema))
    return [schema for *_, schema in sorted(ranked, key=lambda r: r[:3])]


def search_main(argv: list[str]) -> None:
    ap = argparse.ArgumentParser(
        prog="cfn-typegen search",
        description="Find resource types by words in their name or description, then pass the names to cfn-typegen.",
    )
    ap.add_argument("terms", nargs="+", help="words that must all match, e.g. load balancer")
    ap.add_argument("--limit", type=int, default=20, help="most results to show (default 20)")
    ap.add_argument("--schemas", type=Path, default=CACHE, help="CloudformationSchema.zip (downloaded if missing)")
    ap.add_argument("--refresh", action="store_true", help="download the schemas again, picking up new AWS resources")
    args = ap.parse_args(argv)

    found = search(load_schemas(ensure_schemas(args.schemas, args.refresh)), args.terms)
    shown = found[: args.limit]
    width = max((len(s["typeName"]) for s in shown), default=0)
    columns = shutil.get_terminal_size((100, 24)).columns
    for schema in shown:
        desc = short(schema.get("description")) or ""
        desc = "" if _BOILERPLATE.fullmatch(desc) else desc
        room = max(columns - width - 3, 0)
        print(f"{schema['typeName']:<{width}}  {desc[:room]}".rstrip())
    sys.stdout.flush()
    if not found:
        sys.exit(f"no resource type matches: {' '.join(args.terms)}")
    more = f" (showing {len(shown)}, use --limit)" if len(found) > len(shown) else ""
    print(f"\n{len(found)} match{'es' if len(found) != 1 else ''}{more}. Generate with: cfn-typegen --out DIR <type>...", file=sys.stderr)


def load_config(path: Path) -> dict[str, Any]:
    """Settings from a TOML file; its relative paths (`out`, `templates`, `schemas`) are resolved against its directory."""
    config = tomllib.loads(path.read_text())
    for key in ("out", "schemas"):
        if key in config:
            config[key] = str(path.parent / config[key])
    if "templates" in config:
        config["templates"] = [str(path.parent / t) for t in config["templates"]]
    return config


def main(argv: list[str] | None = None) -> None:
    argv = sys.argv[1:] if argv is None else argv
    if argv[:1] == ["search"]:
        return search_main(argv[1:])
    if argv[:1] == ["init-repo"]:
        from cfn_typed.scaffold import init_repo_main

        return init_repo_main(argv[1:])
    ap = argparse.ArgumentParser(prog="cfn-typegen", description="Generate typed CloudFormation resource modules.", epilog="Not sure of a type name? Run: cfn-typegen search WORD...\nStarting a package of generated types? Run: cfn-typegen init-repo NAME")
    ap.add_argument("types", nargs="*", help="resource types or globs, e.g. AWS::SQS::Queue or 'AWS::Lambda::*'")
    ap.add_argument("--config", type=Path, help="TOML file with out, types, all, templates, docs, schemas (default: ./cfn-typegen.toml if present)")
    ap.add_argument("--out", type=Path, help="directory to write the modules into (default: `out` in the config file)")
    ap.add_argument("--template", type=Path, action="append", default=[], help="JSON template; emit the types it uses")
    ap.add_argument("--all", action="store_true", help="emit every resource type")
    ap.add_argument("--no-docs", action="store_true", help="leave the description docstrings out (much smaller output)")
    ap.add_argument("--no-constraints", action="store_true", help="leave out the CONSTRAINTS, ATTRIBUTES and RULES tables that the template checks read (smaller output)")
    ap.add_argument("--literal-enums", action="store_true", help="type properties that have a fixed set of values as Literal[...]; AWS adding a value is a type error until you regenerate")
    ap.add_argument("--schemas", type=Path, default=CACHE, help="CloudformationSchema.zip (downloaded if missing)")
    ap.add_argument("--refresh", action="store_true", help="download the schemas again, picking up new AWS resources")
    ap.add_argument("--sam", metavar="TAG", help="also generate AWS::Serverless::* from this SAM release, e.g. v1.116.0 (or `sam` in the config file)")
    args = ap.parse_args(argv)

    config_path = args.config or Path("cfn-typegen.toml")
    if args.config and not config_path.is_file():
        ap.error(f"no such config file: {config_path}")
    config = load_config(config_path) if config_path.is_file() else {}
    named = bool(args.types or args.template or args.all)  # types named on the command line replace the file's
    out = args.out or (Path(config["out"]) if "out" in config else None)
    if out is None:
        ap.error("pass --out, or set `out` in the config file")
    templates = args.template if named else [Path(t) for t in config.get("templates", [])]
    patterns = (args.types if named else config.get("types", [])) + [t for path in templates for t in template_types(path)]
    everything = args.all if named else config.get("all", False)
    if not patterns and not everything:
        ap.error("name resource types, pass --template, use --all, or list `types` in the config file")
    docs = not args.no_docs and config.get("docs", True)
    zip_path = ensure_schemas(args.schemas if args.schemas != CACHE or "schemas" not in config else Path(config["schemas"]), args.refresh)
    schemas = load_schemas(zip_path)
    stamp = schema_stamp(zip_path)
    if sam := args.sam or config.get("sam"):
        schemas += load_sam(ensure_sam(sam, args.refresh))
        stamp += f" sam:{sam}"
    write(out, schemas if everything else select(schemas, patterns), docs=docs, stamp=stamp, overrides=Overrides.of(config.get("optional", []), config.get("required", []), config.get("unconstrained", [])),
          constraints=config.get("constraints", True) and not args.no_constraints, literal_enums=args.literal_enums or config.get("literal_enums", False), universe=schemas)


if __name__ == "__main__":
    main()
